import { readFile, readdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { sqlStatements } from './sql-statements';

// Control-plane migrations must never be installed in a Space's operational schema.
const controlMigrations = new Set([
  '013_workspaces.sql',
  '014_workspace_preferences.sql',
  '015_workspace_slugs.sql',
]);
const names = (await readdir('db/migrations'))
  .filter((n) => /^\d+_[a-z_]+\.sql$/.test(n) && !controlMigrations.has(n))
  .sort();
const bundle = [];
for (const name of names) {
  const sql = (await readFile('db/migrations/' + name, 'utf8')).replaceAll('\r\n', '\n');
  bundle.push({
    name,
    checksum: createHash('sha256').update(sql).digest('hex'),
    statements: sqlStatements(sql),
  });
}
await writeFile(
  'src/server/workspaces/schema-bundle.ts',
  '// Generated by npm run db:bundle. Control-plane migrations are excluded.\nexport const operationalMigrations = ' +
    JSON.stringify(bundle, null, 2) +
    ' as const;\n',
);
console.log('Bundled ' + bundle.length + ' operational migrations.');
