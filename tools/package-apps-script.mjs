import fs from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import crypto from 'node:crypto';

const root = path.resolve(import.meta.dirname, '..');
const source = path.join(root, 'apps-script');
const destination = path.join(root, 'artifacts', 'apps-script');
const backends = (await fs.readdir(source)).filter(name => name.endsWith('.gs')).sort();
backends.splice(backends.indexOf('Config.gs'), 1);
backends.unshift('Config.gs');
const sections = await Promise.all(backends.map(async name => '// Source: apps-script/' + name + '\n' + await fs.readFile(path.join(source, name), 'utf8')));
const code = '// Generated by npm run package:apps-script. Edit apps-script/ sources.\n' + sections.join('\n\n');
new vm.Script(code, { filename: 'Code.gs' });
await fs.mkdir(destination, { recursive: true });
await fs.writeFile(path.join(destination, 'Code.gs'), code);
const files = ['Code.gs', 'Index.html', 'Styles.html', 'Scripts.html', 'appsscript.json'];
for (const name of files.slice(1)) await fs.copyFile(path.join(source, name), path.join(destination, name));
const hashes = await Promise.all(files.map(async name => {
  const bytes = await fs.readFile(path.join(destination, name));
  return crypto.createHash('sha256').update(bytes).digest('hex') + '  ' + name;
}));
await fs.writeFile(path.join(destination, 'SHA256SUMS.txt'), hashes.join('\n') + '\n');
console.log('Prepared artifacts/apps-script/: five production files, no demo or credentials.');
